        descriptions=['기간별 기술점수와 수익률·변동성 종합','현재 진입 조건 관찰','상승 가속과 과열·변동성 균형','하락 후 지지 및 회복','상승 추세 중 조정 후 회복','저항 돌파와 거래량','최근 5거래일 상승률','최근 20거래일 상승률','연율 변동성이 낮은 순서']
